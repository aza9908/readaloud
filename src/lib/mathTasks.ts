/** Задачи для класса и уровня. */
export function tasksFor(grade: Grade, difficulty?: Difficulty): MathTask[] {
  return MATH_TASKS.filter(
    (t) => t.grade === grade && (!difficulty || t.difficulty === difficulty),
  );
}

/** Класс по возрасту — чтобы сразу открыть подходящий раздел. */
export function gradeForAge(age: number): Grade {
  if (age <= 7) return 1;
  if (age === 8) return 2;
  if (age === 9) return 3;
  return 4;
}
