function plural(item: string, n: number): string {
  const [few, many] = PLURAL[item] ?? [item, item];
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return item;
  if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return few;
  return many;
}

