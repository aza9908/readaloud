/** Награда по уровню. */
const COINS: Record<Difficulty, number> = { A: 15, B: 30, C: 60 };

/**
 * Комплект задач на день. Всегда один и тот же в течение суток и разный
 * назавтра — ребёнок не может «перекрутить» набор, закрыв приложение.
 */
export function dailyTasks(grade: Grade, day = dayNumber()): MathTask[] {
  const out: MathTask[] = [];
  // Состав дня: три базовых, две средних, одна олимпиадная — ровно шесть,
  // столько же, сколько разрешено проверок в день.
  const plan: Difficulty[] = ["A", "A", "A", "B", "B", "C"];
  const seen = new Set<string>();

  plan.forEach((diff, i) => {
    const builders = BUILDERS[grade][diff];
    let built: Built | null = null;

    /**
     * Подбираем задачу, не повторяющую уже выбранные в этом же дне.
     * Без этого в комплект попадали две почти одинаковые задачи подряд —
     * ребёнок решает «Вычисли 8×9» дважды и справедливо решает, что
     * приложение сломано. Перебираем варианты, сдвигая зерно; после
     * нескольких попыток берём что есть, чтобы не зациклиться.
     */
    for (let attempt = 0; attempt < 12; attempt++) {
      const r = rng(hash(`bookser:${day}:${grade}:${diff}:${i}:${attempt}`));
      // Чередуем шаблоны, а не берём случайный: так внутри уровня
      // гарантированно встречаются разные типы задач.
      const b = builders[(i + attempt) % builders.length](r);
      const key = `${b.topic}:${b.text.slice(0, 24)}`;
      if (!seen.has(key)) { built = b; seen.add(key); break; }
      built = b;
    }
    if (!built) return;

    out.push({
      id: `d${day}-g${grade}-${i}`,
      grade, difficulty: diff, topic: built.topic,
      text: built.text, answer: built.answer, hint: built.hint,
      coins: COINS[diff],
    });
  });
  return out;
}

