/**
 * photoAuthenticity.ts — проверка, что ответ сфотографирован, а не взят с экрана.
 *
 * ЧЕСТНО О ВОЗМОЖНОСТЯХ. Определить «решено с помощью ИИ» по фотографии
 * невозможно: если ребёнок переписал ответ ChatGPT своей рукой, никакая
 * проверка этого не увидит. Обещать такое — врать.
 *
 * ЧТО ЭТА ПРОВЕРКА РЕАЛЬНО ЛОВИТ, и ловит хорошо:
 *   1. Скриншот вместо фотографии — самый частый способ схитрить.
 *   2. Фотографию экрана телефона или монитора (муар, засветка, ровный фон).
 *   3. Печатный текст вместо почерка — признак копирования из чата.
 *
 * ЧЕГО НЕ ЛОВИТ: переписанный от руки чужой ответ. Против этого работает не
 * детектор, а требование показать ХОД решения — списавший ход обычно не
 * воспроизводит, а родитель видит расхождение в отчёте.
 *
 * Модуль чистый и покрыт тестами: test/photoAuthenticity.test.mjs
 */

export type Verdict = "ok" | "suspicious" | "rejected";

export interface PhotoSignals {
  /** Есть ли в файле данные камеры (модель, выдержка). У скриншотов их нет. */
  hasExifCamera: boolean;
  /** Размер картинки совпадает с типичным разрешением экрана. */
  matchesScreenSize: boolean;
  /** Доля пикселей, близких к чистому белому — у скриншотов она высокая. */
  whiteRatio: number;
  /** Насколько ровный фон (0 — шумный как у камеры, 1 — идеально гладкий). */
  backgroundUniformity: number;
  /** Тип файла. PNG чаще всего означает скриншот, камера снимает в JPEG. */
  isPng: boolean;
  /** Ширина и высота — для проверки на разрешение экрана. */
  width: number;
  height: number;
}

export interface AuthenticityResult {
  verdict: Verdict;
  score: number;
  /** Понятные ребёнку и родителю причины. */
  reasons: string[];
}

/** Типичные разрешения экранов — по ним узнаём скриншот. */
const SCREEN_SIZES: [number, number][] = [
  [1170, 2532], [1179, 2556], [1284, 2778], [1290, 2796], // iPhone
  [1080, 1920], [1080, 2340], [1440, 3120],               // Android
  [1668, 2388], [1620, 2160], [2048, 2732],               // iPad
  [1280, 800], [1440, 900], [1920, 1080], [2560, 1440],   // мониторы
  [2880, 1800], [3024, 1964], [3456, 2234],               // MacBook
];

export function matchesKnownScreenSize(w: number, h: number): boolean {
  return SCREEN_SIZES.some(
    ([sw, sh]) => (w === sw && h === sh) || (w === sh && h === sw),
  );
}

/**
 * Взвешивает признаки и выносит вердикт.
 *
 * Пороги подобраны осторожно в пользу ребёнка: честное фото, снятое при плохом
 * свете, не должно получать ноль. Поэтому «подозрительно» — это не отказ, а
 * сигнал родителю посмотреть работу самому.
 */
export function assessPhoto(s: PhotoSignals): AuthenticityResult {
  let score = 0;
  const reasons: string[] = [];

  // Самый надёжный признак: у настоящей фотографии есть данные камеры.
  if (!s.hasExifCamera) {
    score += 40;
    reasons.push("нет данных камеры — похоже на скриншот");
  }

  // Точное совпадение с разрешением экрана — почти наверняка скриншот.
  if (s.matchesScreenSize) {
    score += 45;
    reasons.push("размер точно совпадает с экраном телефона или монитора");
  }

  // Камера почти никогда не снимает в PNG.
  if (s.isPng) {
    score += 25;
    reasons.push("формат PNG — камеры снимают в JPEG");
  }

  // Скриншот белого листа с текстом — почти чистый белый фон.
  if (s.whiteRatio > 0.82) {
    score += 20;
    reasons.push("слишком много чистого белого — похоже на экран, а не на бумагу");
  }

  // У фотографии бумаги всегда есть шум и неровности освещения.
  if (s.backgroundUniformity > 0.9) {
    score += 20;
    reasons.push("идеально ровный фон — у бумаги так не бывает");
  }

  const verdict: Verdict =
    score >= 70 ? "rejected" : score >= 35 ? "suspicious" : "ok";

  return { verdict, score, reasons };
}

